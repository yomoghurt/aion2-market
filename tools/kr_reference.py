def main(src_dir: str, out: str) -> int:
    src = Path(src_dir)
    aeid = json.loads((src / "kr_aeid_graph.json").read_text(encoding="utf-8"))
    glob = json.loads((src / "global_series.json").read_text(encoding="utf-8"))
    kina = json.loads((src / "kr_kina_krw_siel.json").read_text(encoding="utf-8"))

    items = []
    for key, q in KR_QUOTES.items():
        rec = aeid.get(q["name"]) or {}
        weekly = {}
        for fac in ("asmo", "elyos"):  # 両陣営の週平均。両方あれば平均する
            for p in rec.get(f"{fac}_week") or []:
                if isinstance(p, dict) and p.get("avgPrice"):
                    weekly.setdefault(p["date"][:10], []).append(float(p["avgPrice"]))
        kr_weekly = [[wk("KR", d), round(sum(v) / len(v))] for d, v in sorted(weekly.items())]
        if key in AEID_UNRELIABLE:
            kr_weekly = []
        g = (glob.get("items") or {}).get(key)
        gl = []
        if g:
            by = {}
            for ser in g["series"].values():
                for p in ser:
                    if p.get("med"):
                        by.setdefault(p["d"], []).append(p["med"])
            for d, v in sorted(by.items()):
                v.sort()
                gl.append([wk("GL", d), round(v[len(v) // 2])])
        fc = FORECAST.get(key)
        items.append({
            "key": int(key), "en": q["name"], "ja": q["ja"], "kr": q["kr"],
            "krq": [[wk("KR", d), p, s, note] for d, p, s, note in q["pts"]],
            "krw": kr_weekly, "gl_naeu": gl,
            "fc": {"dir": fc[0], "when": fc[1], "head": fc[2], "conf": fc[3], "why": fc[4]} if fc else None,
        })

    kina_pts = []
    for p in kina:
        d = datetime.fromtimestamp(p["time"], timezone.utc).date().isoformat()
        kina_pts.append([wk("KR", d), round(p["close"])])

    doc = {
        "launch": {k: v.isoformat() for k, v in LAUNCH.items()},
        "global_snapshot": glob.get("pulled_at"),
        "events": {
            "KR": [[wk("KR", d), d, t] for d, t in KR_EVENTS],
            "GL": [[wk("GL", d), d, t] for d, t in GL_EVENTS],
        },
        "kina_krw": kina_pts,
        "forecast_date": "2026-10-28",
        "outlook": OUTLOOK,
        "items": items,
        "sources": [
            "https://github.com/shizukaziye/aion2-market-history",
            "https://aeid.gg/",
            "https://gamebit.co.kr/aion",
        ],
    }
    Path(out).write_text(json.dumps(doc, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"{len(items)} items -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:3]))
